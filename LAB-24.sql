--5. CREATE A STORED PROCEDURE TO DISPLAY TOP N HIGHEST PAID EMPLOYEES FROM EACH DEPARTMENT (VALUE OF N
--IS ENTERED BY USER).
CREATE OR ALTER PROCEDURE SP_TOP_N_EMPLOYEE
@N INT
AS
BEGIN
SELECT * FROM
(
SELECT *,ROW_NUMBER() OVER
(PARTITION BY DEPARTMENT ORDER BY SALARY DESC) AS RN
FROM EMPLOYEE
) X
WHERE RN<=@N;
END

EXEC SP_TOP_N_EMPLOYEE 2;
--6. CREATE A STORED PROCEDURE TO INCREASE SALARY DEPARTMENT-WISE BY A GIVEN PERCENTAGE. (USER ENTER
--DEPARTMENT NAME AND %, E.G. COMPUTER 10).
CREATE OR ALTER PROCEDURE SP_INCREASE_SALARY
@DEPARTMENT VARCHAR(50),@PERCENT DECIMAL(5,2)
AS
BEGIN
UPDATE EMPLOYEE
SET SALARY=SALARY+(SALARY*@PERCENT/100)
WHERE DEPARTMENT=@DEPARTMENT;
END

EXEC SP_INCREASE_SALARY 'COMPUTER',10;
