--12. CREATE A STORED PROCEDURE THAT ACCEPTS A NUMBER AS INPUT AND DISPLAYS THE TOP N MOST EXPENSIVE BOOKS
--WITH AUTHOR AND PUBLISHER DETAILS.

CREATE OR ALTER PROCEDURE SP_TOP_N_EXPENSIVE_BOOKS
@N INT
AS
BEGIN
SELECT TOP (@N) B.*,A.AUTHORNAME,P.PUBLISHERNAME
FROM BOOK B
JOIN AUTHOR A ON B.AUTHORID=A.AUTHORID
JOIN PUBLISHER P ON B.PUBLISHERID=P.PUBLISHERID
ORDER BY B.PRICE DESC;
END

EXEC SP_TOP_N_EXPENSIVE_BOOKS 5;
