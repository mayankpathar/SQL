--2. IMPLEMENT SCALAR FUNCTION TO CALCULATE SIMPLE INTEREST.
CREATE FUNCTION FN_CALCULATE_SIMPLE_INTEREST
(
    @P FLOAT,
    @R FLOAT,
    @T FLOAT
)
RETURNS FLOAT
AS
BEGIN
    RETURN (@P * @R * @T) / 100
END

SELECT DBO.FN_CALCULATE_SIMPLE_INTEREST(10000, 5, 2)

--3. IMPLEMENT SCALAR FUNCTION TO FIND DIFFERENCE IN DAYS BETWEEN TWO DATES.
CREATE FUNCTION FN_DATE_DIFFERENCE
(
    @DATE1 DATE,
    @DATE2 DATE
)
RETURNS INT
AS
BEGIN
    RETURN DATEDIFF(DAY, @DATE1, @DATE2)
END

SELECT dbo.FN_DATE_DIFFERENCE('2026-01-11', '2026-09-21')

