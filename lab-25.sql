--11. IMPLEMENT SCALAR FUNCTION TO RETURN HIGHEST SALARY FROM A GIVEN DEPARTMENT.
CREATE FUNCTION FN_HIGH_SALARY
(
    @DEPARTMENT VARCHAR(50)
)
RETURNS TABLE
AS
RETURN
(
    SELECT MAX(SALARY) AS HIGHEST_SALARY
    FROM EMPLOYEE
    WHERE DEPARTMENT = @DEPARTMENT
)

