--6. IMPLEMENT SCALAR FUNCTION TO CALCULATE FACTORIAL OF GIVEN NUMBER.
CREATE FUNCTION FN_FACTORIAL
(
    @N INT
)
RETURNS BIGINT
AS
BEGIN
    DECLARE @FACT BIGINT = 1
    DECLARE @I INT = 1

    WHILE @I <= @N
    BEGIN
        SET @FACT = @FACT * @I
        SET @I = @I + 1
    END

    RETURN @FACT
END

SELECT dbo.FN_FACTORIAL(5)

--7. IMPLEMENT SCALAR FUNCTION TO CHECK PALINDROME NUMBER.

CREATE FUNCTION FN_PALINDROME
(
    @N INT
)
RETURNS VARCHAR(20)
AS
BEGIN
    DECLARE @TEMP INT = @N
    DECLARE @REV INT = 0
    DECLARE @REM INT

    WHILE @TEMP > 0
    BEGIN
        SET @REM = @TEMP % 10
        SET @REV = (@REV * 10) + @REM
        SET @TEMP = @TEMP / 10
    END

    IF @N = @REV
        RETURN 'Palindrome'

    RETURN 'Not Palindrome'
END

SELECT dbo.FN_PALINDROME(121)

--8. IMPLEMENT SCALAR FUNCTION TO FIND MAXIMUM OF THREE NUMBERS.
CREATE FUNCTION FN_MAX_THREE
(
    @A INT,
    @B INT,
    @C INT
)
RETURNS INT
AS
BEGIN
    DECLARE @MAX INT

    SET @MAX = @A

    IF @B > @MAX
        SET @MAX = @B

    IF @C > @MAX
        SET @MAX = @C

    RETURN @MAX
END

SELECT dbo.FN_MAX_THREE(10, 25, 15)

