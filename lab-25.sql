--5. IMPLEMENT SCALAR FUNCTION TO PRINT NUMBERS FROM 1 TO N.
CREATE FUNCTION FN_PRINT_NUMBERS
(
@N INT
)
RETURNS VARCHAR(MAX)
AS
BEGIN
    DECLARE @PRINT VARCHAR(MAX) ='';
    DECLARE @I INT = 1
      WHILE @I <= @N
    BEGIN
        SET @PRINT = @PRINT + CAST(@I AS VARCHAR) + ' '
        SET @I = @I + 1
    END

    RETURN @PRINT
END

SELECT dbo.FN_PRINT_NUMBERS(10)

